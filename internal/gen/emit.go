package gen

import (
	"fmt"
	"go/format"
	"slices"
	"strconv"
	"strings"
)

// Emit renders the built-in table as Go source for package serverdef.
// The output is gofmt'd and deterministic: map keys are sorted, the
// server order is the curation's, and nothing in it depends on the
// machine it ran on — no timestamp, no path, no environment. A
// generator whose output changes without its input changing cannot be
// checked in, and a table that is not checked in cannot be reviewed.
func Emit(builtins []*Builtin) ([]byte, error) {
	var b strings.Builder

	b.WriteString("// Code generated by internal/gen from the vendored " + CorpusName + " corpus.\n")
	b.WriteString("// DO NOT EDIT — run `go generate ./internal/serverdef/` instead.\n")
	b.WriteString("//\n")
	fmt.Fprintf(&b, "// Corpus:   %s @ %s\n", CorpusName, CorpusCommit)
	fmt.Fprintf(&b, "// Upstream: %s\n", CorpusUpstream)
	fmt.Fprintf(&b, "// License:  %s — see %s/LICENSE.md and ATTRIBUTION\n", CorpusLicense, CorpusSnapshot)
	fmt.Fprintf(&b, "// Snapshot: %s (checked in; generation reads nothing else and\n", CorpusSnapshot)
	b.WriteString("//           reaches no network)\n")
	b.WriteString("//\n")
	b.WriteString("// Each definition below says which of its keys came from the corpus,\n")
	b.WriteString("// which were curated and why, and what the corpus says that this table\n")
	b.WriteString("// deliberately does not carry. See internal/gen/curate.go for the\n")
	b.WriteString("// policy behind those choices.\n\n")
	b.WriteString("package serverdef\n\n")

	b.WriteString("// generatedProvenance records where the defaults came from, so that\n")
	b.WriteString("// `lightspeed servers` and `lightspeed doctor` can attribute them\n")
	b.WriteString("// without hard-coding the corpus anywhere else.\n")
	b.WriteString("var generatedProvenance = Provenance{\n")
	fmt.Fprintf(&b, "\tCorpus:   %s,\n", strconv.Quote(CorpusName))
	fmt.Fprintf(&b, "\tUpstream: %s,\n", strconv.Quote(CorpusUpstream))
	fmt.Fprintf(&b, "\tCommit:   %s,\n", strconv.Quote(CorpusCommit))
	fmt.Fprintf(&b, "\tLicense:  %s,\n", strconv.Quote(CorpusLicense))
	fmt.Fprintf(&b, "\tSnapshot: %s,\n", strconv.Quote(CorpusSnapshot))
	b.WriteString("}\n\n")

	b.WriteString("// generatedBuiltins is the built-in default layer of PLAN §6 item 3:\n")
	b.WriteString("// the servers that answer on a clean machine with no configuration at\n")
	b.WriteString("// all, as long as their binaries are on PATH (item 4).\n")
	b.WriteString("var generatedBuiltins = []*ServerDef{\n")
	for _, built := range builtins {
		emitBuiltin(&b, built)
	}
	b.WriteString("}\n")

	src, err := format.Source([]byte(b.String()))
	if err != nil {
		return nil, fmt.Errorf("generated source does not parse: %w", err)
	}
	return src, nil
}

func emitBuiltin(b *strings.Builder, built *Builtin) {
	def := built.Def
	fmt.Fprintf(b, "\t// %s — %s/lsp/%s.lua\n", def.Name, CorpusName, built.Corpus)
	emitNoteList(b, "\t", "from the corpus", []Note{{Key: strings.Join(built.FromCorpus, ", ")}})
	emitNoteList(b, "\t", "curated", built.Curated)
	emitNoteList(b, "\t", "not imported", built.NotImported)

	b.WriteString("\t{\n")
	b.WriteString("\t\tSchemaVersion: SchemaVersion,\n")
	fmt.Fprintf(b, "\t\tName:          %s,\n", strconv.Quote(def.Name))
	b.WriteString("\t\tActivation: Activation{\n")
	emitStrings(b, "\t\t\t", "Languages", def.Activation.Languages)
	emitStrings(b, "\t\t\t", "Globs", def.Activation.Globs)
	emitStrings(b, "\t\t\t", "RootMarkers", def.Activation.RootMarkers)
	b.WriteString("\t\t\tPriority:    DefaultPriority,\n")
	b.WriteString("\t\t},\n")
	b.WriteString("\t\tServer: Server{\n")
	emitStrings(b, "\t\t\t", "Command", def.Server.Command)
	b.WriteString("\t\t\tTransport:   TransportStdio,\n")
	if len(def.Server.InitializationOptions) > 0 {
		b.WriteString("\t\t\tInitializationOptions: ")
		emitTable(b, "\t\t\t", def.Server.InitializationOptions)
		b.WriteString(",\n")
	}
	if len(def.Server.Settings) > 0 {
		b.WriteString("\t\t\tSettings: ")
		emitTable(b, "\t\t\t", def.Server.Settings)
		b.WriteString(",\n")
	}
	b.WriteString("\t\t},\n")
	if def.Install.Mise != "" {
		fmt.Fprintf(b, "\t\tInstall: Install{Mise: %s},\n", strconv.Quote(def.Install.Mise))
	}
	b.WriteString("\t},\n")
}

// emitNoteList writes a comment block, wrapped, so that a long reason
// stays readable in the generated file rather than running off the page.
func emitNoteList(b *strings.Builder, indent, heading string, notes []Note) {
	if len(notes) == 0 {
		return
	}
	fmt.Fprintf(b, "%s//   %s:\n", indent, heading)
	for _, n := range notes {
		text := n.Key
		if n.Reason != "" {
			if text != "" {
				text += " — " + n.Reason
			} else {
				text = n.Reason
			}
		}
		for i, line := range wrap(text, 62) {
			prefix := "//     "
			if i > 0 {
				prefix = "//       "
			}
			fmt.Fprintf(b, "%s%s%s\n", indent, prefix, line)
		}
	}
}

// wrap breaks text into lines of at most width characters, on spaces.
func wrap(text string, width int) []string {
	words := strings.Fields(text)
	if len(words) == 0 {
		return nil
	}
	var lines []string
	line := words[0]
	for _, w := range words[1:] {
		if len(line)+1+len(w) > width {
			lines = append(lines, line)
			line = w
			continue
		}
		line += " " + w
	}
	return append(lines, line)
}

func emitStrings(b *strings.Builder, indent, field string, values []string) {
	if len(values) == 0 {
		return
	}
	fmt.Fprintf(b, "%s%s: []string{\n", indent, field)
	for _, v := range values {
		fmt.Fprintf(b, "%s\t%s,\n", indent, strconv.Quote(v))
	}
	fmt.Fprintf(b, "%s},\n", indent)
}

// emitTable writes a map[string]any literal with sorted keys.
func emitTable(b *strings.Builder, indent string, table map[string]any) {
	b.WriteString("map[string]any{\n")
	keys := make([]string, 0, len(table))
	for k := range table {
		keys = append(keys, k)
	}
	slices.Sort(keys)
	for _, k := range keys {
		fmt.Fprintf(b, "%s\t%s: ", indent, strconv.Quote(k))
		emitValue(b, indent+"\t", table[k])
		b.WriteString(",\n")
	}
	fmt.Fprintf(b, "%s}", indent)
}

func emitValue(b *strings.Builder, indent string, v any) {
	switch v := v.(type) {
	case map[string]any:
		emitTable(b, indent, v)
	case string:
		b.WriteString(strconv.Quote(v))
	case bool:
		b.WriteString(strconv.FormatBool(v))
	case int64:
		b.WriteString(strconv.FormatInt(v, 10))
	case float64:
		b.WriteString(strconv.FormatFloat(v, 'g', -1, 64))
	case nil:
		b.WriteString("nil")
	default:
		fmt.Fprintf(b, "%#v", v)
	}
}
